// 已解锁的技能（定道后：第 i 个技能在境界 ≥ i 时解锁）
function skillsOf(p) {
  if (!p.dao || !DAO_SKILLS[p.dao]) return [];
  return DAO_SKILLS[p.dao].filter((s) => p.realm >= s.tier);
}
function skillFx(p, key) {
  let v = 0;
  for (const s of skillsOf(p)) if (s.kind === 'u') v += s.fx[key] || 0;
  return v;
}
// 某个战斗技能在这场战斗里值多少（用来挑出最合适的两个施展）
function skillBonus(s, foeDao) {
  const e = s.e, fw = foeDao ? daoWx(foeDao) : null, fp = foeDao ? DAOS[foeDao].pol : null;
  let a = e.a || 0;
  if (e.ve && fw === e.ve[0]) a += e.ve[1];
  if (e.vp && fp === e.vp[0]) a += e.vp[1];
  if (e.w && G.sect.weather === e.w[0]) a += e.w[1];
  if (e.s && sectSeason() === e.s[0]) a += e.s[1];
  if (e.moon && fullMoon()) a += e.moon;
  return { a, c: e.c || 0, cr: e.cr || null, lo: e.lo || 0 };
}
// 战斗：挑两个最合适的战斗技能施展；护体类（d）被动生效，取最高
function useSkills(p, foeDao) {
  const cs = skillsOf(p).filter((s) => s.kind === 'c');
  let def = 0;
  for (const s of cs) def = Math.max(def, s.e.d || 0);
  const scored = cs.map((s) => { const b = skillBonus(s, foeDao); return { s, b, score: b.a + b.c * 1.2 + (b.cr ? b.cr[0] * b.cr[1] : 0) }; })
    .filter((x) => x.score > 0).sort((x, y) => y.score - x.score).slice(0, 2);
  let mul = 1, foeMul = 1, lo = 0;
  const used = [];
  for (const { s, b } of scored) {
    let a = b.a, crit = false;
    if (b.cr && Math.random() < b.cr[0]) { a += b.cr[1]; crit = true; }
    mul *= 1 + a;
    foeMul *= 1 - b.c;
    lo += b.lo;
    used.push('「' + s.n + '」' + (crit ? '（触发！）' : ''));
  }
  return { mul, foeMul: Math.max(0.4, foeMul), def: Math.min(0.6, def), lo, text: used.length ? '施展' + used.join('') : '' };
}
// 每天：医者为全宗受伤同门疗伤；同处一地的同门互相传道
function sectHealPower() {
  const hs = G.sect.people.filter((q) => !q.away && !(q.hurt > 0)).map((q) => skillFx(q, 'healOthers')).filter((v) => v > 0).sort((a, b) => b - a);
  if (!hs.length) return 0;
  return Math.min(5, hs[0] + 0.3 * hs.slice(1).reduce((s, v) => s + v, 0)); // 最强的医者全额，其余 30%，最多每天 5 天
}
function auraAt(p) {
  let v = 0;
  const loc = taskLoc(p);
  for (const q of G.sect.people) if (q !== p && !q.away && q.at === loc && taskLoc(q) === loc) v = Math.max(v, skillFx(q, 'aura'));
  return v;
}
