function rcDynText(ev, p) {
  const pool = RC_DYN[ev];
  if (!pool) return null;
  const R = rdR();
  const sites = Object.values(RD_SITES).filter((s) => !s.trade), mons = Object.values(RD_MONSTERS);
  const parts = RD_PART_LIST.filter((x) => x.tier <= 3 && !x.alien);
  const res = ['fuel', 'food', 'water', 'med', 'ammo', 'scrap'];
  const units = { fuel: '升燃油', food: '份食物', water: '桶水', med: '盒药', ammo: '发子弹', scrap: '块废料' };
  const rk = () => res[Math.floor(Math.random() * res.length)];
  const loot = () => { const k = rk(); return (k === 'ammo' ? 10 + Math.floor(Math.random() * 40) : 2 + Math.floor(Math.random() * 15)) + ' ' + units[k]; };
  const km = Math.max(5, Math.floor((R ? R.km : 0) * (0.5 + Math.random()) + Math.random() * 300));
  return pool[Math.floor(Math.random() * pool.length)].replace(/\{(\w+)\}/g, (_, k) => {
    if (k === 'site') return sites[Math.floor(Math.random() * sites.length)].name;
    if (k === 'mon') return mons[Math.floor(Math.random() * mons.length)].name;
    if (k === 'part') return parts[Math.floor(Math.random() * parts.length)].name;
    if (k === 'loot') return loot();
    if (k === 'res') return RD_RES[rk()].name;
    if (k === 'biome') return RD_BIOMES[Math.floor(Math.random() * RD_BIOMES.length)].name;
    if (k === 'km') return String(km);
    if (k === 'n') return String(2 + Math.floor(Math.random() * 7));
    return (p && p[k]) || '';
  });
}

// 用固定种子生成所有普通 NPC（每局都是同一批人）
function rcRng(seed) { let s = seed >>> 0; return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; }; }
function rcBuildNpcs() {
  const rnd = rcRng(20261119), list = [], used = {};
  const arch = Object.keys(RC_ARCH);
  const pick = (a) => a[Math.floor(rnd() * a.length)];
  const realS = '王李张刘陈杨赵黄周吴徐孙胡朱高林何郭马罗梁宋郑谢韩唐冯于董萧程曹袁邓许傅沈曾彭吕苏卢蒋蔡贾丁魏薛叶阎余潘杜戴夏钟汪田任姜范方石姚谭廖邹熊金陆郝孔白崔康毛邱秦江史顾侯邵孟龙万段雷钱汤尹黎易常武乔贺赖龚文';
  const realG = ['建国', '秀英', '志强', '丽娟', '浩然', '欣怡', '子轩', '雨涵', '伟', '芳', '军', '敏', '磊', '静', '涛', '婷', '鹏', '洁', '超', '燕', '明', '霞', '杰', '红', '强', '玲', '斌', '艳', '博文', '思琪', '宇航', '梓涵', '国庆', '桂兰', '晓东', '春花', '一帆', '诗涵', '家豪', '佳怡'];
  while (list.length < 500) {
    let name;
    const r = rnd();
    if (r < 0.6) name = pick(RC_NAME_A) + pick(RC_NAME_B);
    else if (r < 0.88) name = realS[Math.floor(rnd() * realS.length)] + pick(realG);
    else name = pick(RC_NAME_B) + Math.floor(rnd() * 9000 + 1000);
    if (used[name] || RC_VIP_NAMES[name]) continue;
    used[name] = true;
    const a = arch[list.length % arch.length];
    const lines = {};
    for (const ev in RC_EVENTS) {
      if (ev === 'idle') continue; // 闲聊用整个性格的台词库
      const pool = RC_ARCH[a].lines[ev].split('|');
      const idx = pool.map((_, i) => i).sort(() => rnd() - 0.5);
      lines[ev] = idx.slice(0, 3 + Math.floor(rnd() * 3)); // 每个事件固定 3~5 句
    }
    list.push({ id: 'n' + list.length, name, arch: a, job: pick(RC_JOBS), car: pick(RC_CARS), home: pick(RC_HOMES),
      lines, talk: 0.3 + rnd() * 1.4 });
  }
  return list;
}
